export function normalizeCompetitionMatchKey(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function findCatalogEntryForCompetitionName(
  name: string,
): CompetitionCatalogEntry | null {
  const key = normalizeCompetitionMatchKey(name);
  // Exact alias match first (prefer longer aliases to avoid NPC ⊂ something).
  let best: { entry: CompetitionCatalogEntry; len: number } | null = null;
  for (const entry of COMPETITION_CATALOG) {
    for (const alias of entry.aliases) {
      const a = normalizeCompetitionMatchKey(alias);
      if (a === key) {
        if (!best || a.length > best.len) best = { entry, len: a.length };
      }
    }
  }
  if (best) return best.entry;

  // Short exact aliases only (NPC, URC) — no fuzzy contains.
  for (const entry of COMPETITION_CATALOG) {
    for (const alias of entry.aliases) {
      const a = normalizeCompetitionMatchKey(alias);
      if (a.length <= 4 && a === key) return entry;
    }
  }
  return null;
}

export function groupCompetitionCatalog(): Map<string, CompetitionCatalogEntry[]> {
  const map = new Map<string, CompetitionCatalogEntry[]>();
  for (const entry of COMPETITION_CATALOG) {
    const list = map.get(entry.group) ?? [];
    list.push(entry);
    map.set(entry.group, list);
  }
  return map;
}
