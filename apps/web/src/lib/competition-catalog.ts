/**
 * Rugby365 competition catalog — taxonomy for CMS + future imports.
 * DB rows are only created/updated for competitions that are already populated
 * (seasons, fixtures or standings). Unpopulated catalog entries stay as roadmap.
 */

export type CompetitionGender = "men" | "women" | "mixed";
export type CompetitionAgeGroup = "senior" | "u20" | "u18" | "university" | "schools" | "mixed";
export type CompetitionFormat =
  | "league"
  | "cup"
  | "series"
  | "tour"
  | "championship"
  | "shield"
  | "sevens"
  | "playoff";
export type CompetitionLevel =
  | "international"
  | "continental"
  | "national_top"
  | "national_2"
  | "national_3"
  | "provincial"
  | "regional"
  | "club"
  | "collegiate"
  | "schools";
export type CompetitionSeasonStructure =
  | "northern_split"
  | "southern_calendar"
  | "tournament"
  | "touring"
  | "rolling";
export type CompetitionLifecycle = "current" | "former";

export type CompetitionCatalogEntry = {
  key: string;
  name: string;
  /** Names used to match existing DB competitions. */
  aliases: string[];
  group: string;
  country: string | null;
  region: string;
  gender: CompetitionGender;
  ageGroup: CompetitionAgeGroup;
  format: CompetitionFormat;
  level: CompetitionLevel;
  seasonStructure: CompetitionSeasonStructure;
  lifecycle: CompetitionLifecycle;
  competitionType: "domestic" | "international" | "world_cup" | "european";
};

function e(
  partial: Omit<CompetitionCatalogEntry, "aliases"> & { aliases?: string[] },
): CompetitionCatalogEntry {
  return { aliases: partial.aliases ?? [partial.name], ...partial };
}

